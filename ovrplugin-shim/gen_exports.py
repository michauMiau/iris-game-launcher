def parse_cs():
    s = CS.read_text()
    pat = re.compile(
        r'\[DllImport\(([^\]]*)\)\]\s*(?:\[[^\]]*\]\s*)?(?:public|private) static extern\s+([\w\.<>\[\], ]+?)\s+(\w+)\(([^)]*)\);',
        re.S,
    )
    out = []
    for m in pat.finditer(s):
        attrs, ret, name, args = m.group(1), m.group(2).strip(), m.group(3), m.group(4).strip()
        ep = re.search(r'EntryPoint\s*=\s*"([^"]+)"', attrs)
        if ep:
            name = ep.group(1)
        out.append((name, ret, args))
    return out


def split_args(args):
    args = " ".join(args.split())
    if not args:
        return []
    parts, depth, cur = [], 0, ""
    for ch in args:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    out = []
    for p in parts:
        toks = p.split()
        name = toks[-1]
        ty = " ".join(toks[:-1])
        out.append((name, ty))
    return out


def rust_type(ty, by_value_struct):
    ty = ty.strip()
    if ty.startswith("ref ") or ty.startswith("out "):
        inner = ty[4:].strip()
        return "*mut " + rust_type(inner, by_value_struct)
    base = ty.split("[")[0].strip()
    if base in STRUCTS:
        return base
    if base in TYPE_MAP:
        return TYPE_MAP[base]
    raise SystemExit(f"unknown type: {ty!r}")


def gen():
    declared = parse_cs()
    declared_names = {d[0] for d in declared}
    real_names = [l.strip() for l in REAL.read_text().splitlines() if l.strip()]
    # legacy = real export names not declared by the C# wrapper
    legacy_names = [n for n in real_names if n not in declared_names and n in old_blocks]

    lines = []
    lines.append("// Generated by gen_exports.py from OVRPlugin.cs. Do not edit by hand.")
    lines.append("#![allow(non_snake_case, non_camel_case_types, unused_variables)]")
    lines.append("use crate::abi::*;")
    lines.append("")
    for name, ret, args in declared:
        spec = split_args(args)
        params = ", ".join(f"{an}: {rust_type(at, True)}" for an, at in spec)
        rty = rust_type(ret, True)
        call_args = ", ".join(an for an, _ in spec)
        lines.append("#[no_mangle]")
        lines.append(f'pub extern "C" fn {name}({params}) -> {rty} {{')
        lines.append(f'    crate::trace_call("{name}");')
        if name in core_fns:
            lines.append(f"    crate::core::{name}({call_args})")
        else:
            lines.append(f"    crate::core::default_value::<{rty}>()")
        lines.append("}")
        lines.append("")
    (ROOT / "src" / "exports.rs").write_text("\n".join(lines) + "\n")

    # legacy blocks preserved verbatim from the previous lib.rs
    legacy = ["// Names the C# wrapper never declares; kept so the export table matches the real plugin."]
    for n in legacy_names:
        legacy.append(old_blocks[n])
    # the decorated C++ alias is the 412th export; its name is not a Rust identifier
    legacy.append(
        '#[export_name = "?ovrp_SetFunctionPointer@@YA?AW4ovrpResult@@W4ovrpFunctionType@@PEAX@Z"]\n'
        "pub extern \"C\" fn ovrp_set_function_pointer_alias(\n"
        "    a0: i32,\n"
        "    a1: *mut std::os::raw::c_void,\n"
        ") -> i32 {\n"
        '    crate::trace_call("ovrp_set_function_pointer_alias");\n'
        "    0\n"
        "}\n"
    )
    (ROOT / "src" / "legacy.rs").write_text("\n".join(legacy) + "\n")

    print(f"declared={len(declared)} legacy={len(legacy_names)} core={len(core_fns)}")
    print("legacy names missing from old lib:", [n for n in real_names if n not in declared_names and n not in old_blocks][:10])


