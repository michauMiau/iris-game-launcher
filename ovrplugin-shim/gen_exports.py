def extract_old_blocks():
    s = OLD_LIB.read_text()
    lines = s.splitlines(keepends=True)
    blocks = {}
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.strip() == "#[no_mangle]":
            start = i
            # find signature line(s) until '{'
            j = i + 1
            sig = []
            while j < len(lines) and "{" not in lines[j]:
                sig.append(lines[j])
                j += 1
            if j >= len(lines):
                i += 1
                continue
            sig.append(lines[j])
            # find matching close brace
            depth = 0
            k = j
            while k < len(lines):
                depth += lines[k].count("{") - lines[k].count("}")
                if depth == 0:
                    break
                k += 1
            block = "".join(lines[start : k + 1]).rstrip() + "\n"
            m = re.search(r"\b(\w+)\s*\(", "".join(sig))
            if m:
                blocks[m.group(1)] = block
            i = k + 1
        else:
            i += 1
    return blocks


old_blocks = extract_old_blocks()

