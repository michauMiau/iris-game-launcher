pub enum Lang {
    En,
    Pl,
}

pub fn parse(s: &str) -> Lang {
    match s.trim().to_lowercase().as_str() {
        "pl" | "polski" | "polish" => Lang::Pl,
        _ => Lang::En,
    }
}

